package com.cinecascade.core.cascade

import com.cinecascade.core.model.DiscoveryFilters
import com.cinecascade.core.model.MediaItem
import com.cinecascade.core.model.ThemeVibe
import com.cinecascade.core.repository.MovieRepository
import java.util.concurrent.atomic.AtomicLong

/** One horizontal carousel in the vertical cascade (GDD §4.1). */
data class CarouselNode(
    /** Unique per generated row; UI keys scroll state on it. */
    val id: Long,
    val isThemeRow: Boolean,
    val parentItem: MediaItem? = null,
    val parentTheme: ThemeVibe? = null,
    val themes: List<ThemeVibe> = emptyList(),
    val items: List<MediaItem> = emptyList(),
    val selectedIndex: Int = 0,
) {
    val size: Int get() = if (isThemeRow) themes.size else items.size
    val selectedItem: MediaItem? get() = if (isThemeRow) null else items.getOrNull(selectedIndex)
    val selectedTheme: ThemeVibe? get() = if (isThemeRow) themes.getOrNull(selectedIndex) else null

    /** Id of the focused element (theme id or item id). */
    val selectedKey: String? get() = selectedTheme?.id ?: selectedItem?.id

    /** Label of what generated this row. */
    val parentLabel: String? get() = parentItem?.title ?: parentTheme?.name

    /** Label of the focused element. */
    val selectedLabel: String? get() = selectedTheme?.name ?: selectedItem?.title

    fun keys(): List<String> = if (isThemeRow) themes.map { it.id } else items.map { it.id }

    fun indexOfKey(key: String?): Int = key?.let { keys().indexOf(it) } ?: -1
}

/**
 * The cascade chain: levels[0] is the theme row, levels[activeLevelIndex] is Slot 2, the level
 * above is Slot 1 and the level below (always present) is the live Slot 3 preview. Levels deeper
 * than the preview are kept as "forward history" after going back, until a different choice is made.
 */
data class CascadeTree(
    val levels: List<CarouselNode>,
    val activeLevelIndex: Int,
) {
    val active: CarouselNode get() = levels[activeLevelIndex]
    val previous: CarouselNode? get() = levels.getOrNull(activeLevelIndex - 1)
    val preview: CarouselNode? get() = levels.getOrNull(activeLevelIndex + 1)
    val canGoBack: Boolean get() = activeLevelIndex > 0
    val canAdvance: Boolean get() = (preview?.size ?: 0) > 0

    /** Ids of the items selected along the chain from the root down to (and including) [level]. */
    fun pathIds(level: Int): Set<String> =
        levels.take(level + 1).mapNotNull { it.selectedItem?.id }.toSet()
}

/** Builds rows. Separated from the navigator so the tree logic can be unit-tested. */
interface NodeFactory {
    fun themeRow(): CarouselNode

    /** Row generated by the focused element of [parent]; [pathIds] are titles already on the chain. */
    fun childOf(parent: CarouselNode, pathIds: Set<String>): CarouselNode?
}

class RepositoryNodeFactory(
    private val repository: MovieRepository,
    private val filters: () -> DiscoveryFilters,
) : NodeFactory {
    private val ids = AtomicLong(0)

    override fun themeRow() = CarouselNode(id = ids.incrementAndGet(), isThemeRow = true, themes = repository.themes)

    override fun childOf(parent: CarouselNode, pathIds: Set<String>): CarouselNode? {
        parent.selectedTheme?.let { theme ->
            return CarouselNode(
                id = ids.incrementAndGet(),
                isThemeRow = false,
                parentTheme = theme,
                items = repository.titlesForTheme(theme, filters()),
            )
        }
        val item = parent.selectedItem ?: return null
        val source = repository.item(item.id) ?: item
        return CarouselNode(
            id = ids.incrementAndGet(),
            isThemeRow = false,
            parentItem = source,
            items = repository.findRecommendations(source, filters(), pathIds),
        )
    }
}

/** Pure tree operations (GDD §2.1 & §7.2). Every function returns a new tree. */
class CascadeNavigator(private val factory: NodeFactory) {

    fun initial(): CascadeTree = withPreview(CascadeTree(listOf(factory.themeRow()), 0))

    /** The centred card of [levelIndex] changed. Deeper levels are cut and a fresh preview grows. */
    fun focus(tree: CascadeTree, levelIndex: Int, index: Int): CascadeTree {
        val node = tree.levels.getOrNull(levelIndex) ?: return tree
        if (index !in 0 until node.size) return tree
        if (index == node.selectedIndex && levelIndex == tree.activeLevelIndex) return tree
        val truncated = tree.levels.subList(0, levelIndex + 1).toMutableList()
        truncated[levelIndex] = node.copy(selectedIndex = index)
        return withPreview(CascadeTree(truncated, levelIndex))
    }

    /** Swipe up / tap focused card: Slot 3 becomes Slot 2. */
    fun advance(tree: CascadeTree): CascadeTree {
        if (!tree.canAdvance) return tree
        return withPreview(tree.copy(activeLevelIndex = tree.activeLevelIndex + 1))
    }

    /** Tap on a card in Slot 3: focus it there, then advance. */
    fun advanceTo(tree: CascadeTree, previewIndex: Int): CascadeTree {
        val previewLevel = tree.activeLevelIndex + 1
        val preview = tree.preview ?: return tree
        if (previewIndex !in 0 until preview.size) return tree
        val focused = if (previewIndex == preview.selectedIndex) tree else {
            val levels = tree.levels.subList(0, previewLevel + 1).toMutableList()
            levels[previewLevel] = preview.copy(selectedIndex = previewIndex)
            CascadeTree(levels, tree.activeLevelIndex)
        }
        return advance(focused)
    }

    /** Swipe down / tap Slot 1. Deeper levels are kept so the same path can be re-entered. */
    fun back(tree: CascadeTree): CascadeTree =
        if (tree.canGoBack) tree.copy(activeLevelIndex = tree.activeLevelIndex - 1) else tree

    /** Jump to an earlier level and pick another card there (branch switch). */
    fun branch(tree: CascadeTree, levelIndex: Int, index: Int): CascadeTree {
        if (levelIndex !in tree.levels.indices) return tree
        val node = tree.levels[levelIndex]
        return if (index == node.selectedIndex) {
            withPreview(tree.copy(activeLevelIndex = levelIndex))
        } else {
            focus(tree.copy(activeLevelIndex = levelIndex), levelIndex, index)
        }
    }

    /**
     * Filters changed: rebuild every level below the root in place, keeping the user's selections
     * when they survive the new filters, and the active depth when possible.
     */
    fun rebuild(tree: CascadeTree): CascadeTree {
        val rebuilt = mutableListOf(tree.levels.first())
        for (i in 1..tree.activeLevelIndex + 1) {
            val parent = rebuilt[i - 1]
            val fresh = factory.childOf(parent, rebuiltPath(rebuilt)) ?: break
            if (fresh.size == 0) break
            val old = tree.levels.getOrNull(i)
            val node = when {
                old != null && old.keys() == fresh.keys() && old.parentLabel == fresh.parentLabel -> old
                else -> fresh.copy(selectedIndex = fresh.indexOfKey(old?.selectedKey).coerceAtLeast(0))
            }
            rebuilt += node
        }
        val active = minOf(tree.activeLevelIndex, rebuilt.lastIndex)
        return withPreview(CascadeTree(rebuilt.take(active + 2), active))
    }

    /** Regenerate the Slot 3 preview (e.g. after Gemini added titles). No-op if nothing changed. */
    fun refreshPreview(tree: CascadeTree): CascadeTree {
        val fresh = factory.childOf(tree.active, tree.pathIds(tree.activeLevelIndex)) ?: return tree
        val current = tree.preview
        if (current != null && current.keys() == fresh.keys()) return tree
        return CascadeTree(tree.levels.subList(0, tree.activeLevelIndex + 1) + fresh, tree.activeLevelIndex)
    }

    private fun rebuiltPath(levels: List<CarouselNode>) = levels.mapNotNull { it.selectedItem?.id }.toSet()

    /** Ensures the level below the active one exists (Slot 3). */
    private fun withPreview(tree: CascadeTree): CascadeTree {
        if (tree.preview != null) return tree
        val child = factory.childOf(tree.active, tree.pathIds(tree.activeLevelIndex)) ?: return tree
        return tree.copy(levels = tree.levels + child)
    }
}
